import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

describe('public portfolio atelier', () => {
  const root=resolve('public/explore');
  const html=readFileSync(resolve(root,'index.html'),'utf8');
  const css=readFileSync(resolve(root,'styles.css'),'utf8');
  const data=readFileSync(resolve(root,'data.js'),'utf8');
  const app=readFileSync(resolve(root,'app.js'),'utf8');
  const comparison=readFileSync(resolve(root,'compare.js'),'utf8');
  const journey=readFileSync(resolve(root,'journey.js'),'utf8');
  const lab=readFileSync(resolve(root,'lab-ui.js'),'utf8');
  const labEngine=readFileSync(resolve(root,'lab-engine.js'),'utf8');
  const cases=readFileSync(resolve(root,'casebook.js'),'utf8');
  const blueprints=readFileSync(resolve(root,'blueprints.js'),'utf8');
  it('publishes a dependency-free interactive route', () => {
    expect(existsSync(resolve(root,'favicon.svg'))).toBe(true);
    expect(existsSync(resolve(root,'cover.svg'))).toBe(true);
    expect(html).toContain('id="relationship-graph"');
    expect(html).toContain('id="command-dialog"');
    expect(html).toContain('src="./data.js"');
    expect(html).toContain('src="./app.js"');
    expect(html).toContain('src="./blueprints.js"');
    expect(html).toContain('src="./casebook.js"');
    expect(html).toContain('id="casebook-dialog"');
    expect(blueprints).toContain('migrationwitness');
    expect(cases).toContain('showModal');
    expect(cases).toContain('popstate');
    expect(css).toContain('prefers-reduced-motion');
    expect(app).toContain('setPointerCapture');
    expect(app).toContain('renderCommandResults');
    expect(html).toContain('id="compare-studio"');
    expect(html).toContain('id="mobile-project-index"');
    expect(html).toContain('src="./compare.js"');
    expect(comparison).toContain('data.domains.filter');
    expect(html).toContain('id="lab-workbench"');
    expect(html).toContain('src="./lab-engine.js"');
    expect(html).toContain('src="./lab-ui.js"');
    expect(lab).toContain('selectMode');
    expect(lab).toContain('renderTrace');
    expect(labEngine).toContain('function permission(');
    expect(labEngine).toContain('function retrieval(');
    expect(comparison).toContain('popstate');
    expect(html).toContain('id="journey-launch"');
    expect(html).toContain('id="journey-dialog"');
    expect(html).toContain('src="./journey.js"');
    expect(journey).toContain('KAISER_CASEBOOK');
    expect(journey).toContain('KAISER_LAB');
    expect(journey).toContain('KAISER_COMPARE');
    expect(journey).toContain('searchParams.set("trail"');
    expect(app).toContain('updateMobileIndex');
  });
  it('is personal, bilingual and publicly sourced',()=>{
    expect(data).toContain('Northeast Forestry University');
    expect(data).toContain('东北林业大学');
    expect(data).toContain('CardCraft');
    expect(data).toContain('MigrationWitness');
    expect(html).not.toContain('For recruiters / HR');
    expect(html).not.toContain('Graduate admissions');
    expect(data).not.toContain('KaiserIIII/CampusScopePro');
    expect(data).not.toContain('KaiserIIII/route-utility-gap');
  });
});
